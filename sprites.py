"""Pixel art for the deck creature.

Every frame is an ASCII grid: one character per sprite pixel, resolved through PALETTE.
Edit the grids directly — build_sheet.py validates dimensions and reports the exact
frame and row if anything is off.

Reference row shapes (all 20 columns wide):

    ....................   empty
    .....OOOOOOOOOO.....   body
    .....O##OOOO##O.....   body with eyes
    ...OOOOOOOOOOOOOO...   body with side nubs (also used for squash poses)
    ...OOO##OOOO##OOO...   wide body with eyes (squash poses)
    .....OO..OO..OO.....   three legs

Colours may carry an alpha byte (`#RRGGBBAA`) - used for the ground shadow and puffs.

RESOLUTION
----------
The finished sprite is a 40 x 32 grid. The body is authored at half that (20 x 16) and
doubled by build_sheet.py, because chunky is the whole look and 20 x 16 is where his
proportions were tuned. Props are authored at the full 40 x 32 resolution instead
(`"fine": True`), since they are the things that have to be recognisable - a book drawn
in 7 x 6 cells is the same shape as a brick.

So: body cells are 2 sprite pixels wide, prop cells are 1. Prop anchors in COSTUMES are
in sprite pixels, i.e. the fine grid - double any coordinate you read off a body grid.
The shading and outline passes run after the doubling, which is what keeps the outline
one sprite pixel thick instead of two.
"""

