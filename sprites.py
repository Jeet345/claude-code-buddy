# Automatic depth pass, applied by build_sheet.py before baking.
#   top     - char to use where nothing sits directly above (catches the light)
#   bottom  - char to use where nothing sits directly below (falls into shade)
#   outline - char painted into the transparent cells touching this colour
# Authoring stays flat: one character per shape. The look is derived, so
# changing the light direction is a change here, not across 30 grids.
